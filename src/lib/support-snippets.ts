export function getSnippetText(snippet: SupportSnippet) {
  return snippet.text || snippet.content || "";
}

export function getSnippetTags(snippet: SupportSnippet) {
  return [...snippet.triggers, ...(snippet.tags ?? [])];
}

export function findRelevantSnippets(query: string, limit = 3): SupportSnippet[] {
  const queryLower = query.toLowerCase();

  return SUPPORT_SNIPPETS.map((snippet) => {
    let score = 0;
    for (const trigger of snippet.triggers) {
      if (queryLower.includes(trigger.replaceAll("_", " "))) score += 4;
      if (queryLower.includes(trigger)) score += 4;
    }
    if (queryLower.includes(snippet.category.replaceAll("_", " "))) score += 3;
    if (queryLower.includes(snippet.intent.replaceAll("_", " "))) score += 2;
    if (snippet.title?.toLowerCase().split(/\s+/).some((word) => queryLower.includes(word))) {
      score += 1;
    }
    return { snippet, score };
  })
    .filter((item) => item.score > 0 && item.snippet.tone_reviewed)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((item) => item.snippet);
}
