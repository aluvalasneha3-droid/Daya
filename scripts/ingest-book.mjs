import fs from 'fs';
import path from 'path';

const CONTENT_PATH = path.join(process.cwd(), 'BOOK_CONTENT.md');
const OUTPUT_PATH = path.join(process.cwd(), 'src/lib/daya/book-knowledge.ts');

async function ingest() {
  console.log('📖 Starting book ingestion...');

  if (!fs.existsSync(CONTENT_PATH)) {
    console.error('❌ BOOK_CONTENT.md not found!');
    return;
  }

  const content = fs.readFileSync(CONTENT_PATH, 'utf-8');
  const sections = content.split('###').slice(1); // Split by h3 headers

  if (sections.length === 0) {
    console.warn('⚠️ No content found after "###" headers in BOOK_CONTENT.md');
    return;
  }

  const snippets = sections.map((section, index) => {
    const lines = section.trim().split('\n');
    const title = lines[0].trim();
    const text = lines.slice(1).join('\n').trim();
    
    // Simple trigger extraction from title
    const triggers = title.toLowerCase().split(/\s+/).filter(word => word.length > 3);

    return {
      id: `book-${index}`,
      category: "book_knowledge",
      intent: "parent_tip",
      triggers: triggers,
      source_label: "User Provided Book",
      tone_reviewed: true,
      title: title,
      text: text,
    };
  });

  const tsContent = `import type { SupportSnippet } from "@/types";

/**
 * AUTO-GENERATED from BOOK_CONTENT.md
 * Do not edit this file directly.
 */

export const BOOK_SNIPPETS: SupportSnippet[] = ${JSON.stringify(snippets, null, 2)};

export function findRelevantBookSnippets(query: string, limit = 3): SupportSnippet[] {
  const queryLower = query.toLowerCase();
  
  return BOOK_SNIPPETS.map(snippet => {
    let score = 0;
    for (const trigger of snippet.triggers) {
      if (queryLower.includes(trigger.toLowerCase())) score += 5;
    }
    if (snippet.text.toLowerCase().includes(queryLower)) score += 2;
    if (snippet.title?.toLowerCase().includes(queryLower)) score += 3;
    
    return { snippet, score };
  })
  .filter(item => item.score > 0)
  .sort((a, b) => b.score - a.score)
  .slice(0, limit)
  .map(item => item.snippet);
}
`;

  fs.writeFileSync(OUTPUT_PATH, tsContent);
  console.log(`✅ Ingested ${snippets.length} snippets into ${OUTPUT_PATH}`);
}

ingest();
